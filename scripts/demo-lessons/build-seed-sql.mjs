// Builds database/seeds/demo_lessons.sql from database/demo-lessons/<slug>/lesson.json.
// The seed upserts the canonical lessons by slug (idempotent) and publishes them. Media are not in
// the database: the API serves database/demo-lessons/<slug>/audio.mp3 (and video.mp4) itself.
// Usage: node scripts/demo-lessons/build-seed-sql.mjs [--check]
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const lessonsDir = path.join(root, 'database/demo-lessons');
const target = path.join(root, 'database/seeds/demo_lessons.sql');
const ORDER = ['crase', 'vacinas', 'internet'];

/** Dollar-quoted SQL literal with a tag that never appears in the text. */
function quote(value) {
  const text = String(value);
  let tag = 'demo';
  while (text.includes('$' + tag + '$')) tag += 'x';
  const fence = '$' + tag + '$';
  return fence + text + fence;
}

const slugs = readdirSync(lessonsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(path.join(lessonsDir, entry.name, 'lesson.json')))
  .map((entry) => entry.name)
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99));

const statements = slugs.map((slug, index) => {
  const lesson = JSON.parse(readFileSync(path.join(lessonsDir, slug, 'lesson.json'), 'utf8'));
  if (lesson.slug !== slug) throw new Error(`slug mismatch in ${slug}`);
  const content = {
    segments: lesson.segments,
    words: lesson.words ?? null,
    summary: lesson.summary,
    questions: lesson.questions,
    flashcards: lesson.flashcards,
    credits: lesson.credits,
  };
  const media = lesson.media || {};
  const video = media.video ? quote(`demo/${slug}/${media.video}`) : 'null';
  const videoMime = media.video ? quote(media.videoMime || 'video/mp4') : 'null';
  return [
    'insert into public.demo_lessons (slug, version, title, subject, description, language, cover, duration_ms,',
    '  audio_storage_path, audio_mime, audio_size_bytes, video_storage_path, video_mime, content, published, sort_order)',
    `values (${quote(slug)}, ${Number(lesson.version) || 1}, ${quote(lesson.title)}, ${quote(lesson.subject)}, ${quote(lesson.description || '')},`,
    `  ${quote(lesson.language || 'pt')}, ${quote(JSON.stringify(lesson.cover || {}))}::jsonb, ${Number(lesson.durationMs)},`,
    `  ${quote(`demo/${slug}/${media.audio || 'audio.mp3'}`)}, ${quote(media.audioMime || 'audio/mpeg')}, ${Number(media.sizeBytes)},`,
    `  ${video}, ${videoMime},`,
    `  ${quote(JSON.stringify(content))}::jsonb, true, ${index})`,
    'on conflict (slug) do update set version = excluded.version, title = excluded.title, subject = excluded.subject,',
    '  description = excluded.description, language = excluded.language, cover = excluded.cover,',
    '  duration_ms = excluded.duration_ms, audio_storage_path = excluded.audio_storage_path,',
    '  audio_mime = excluded.audio_mime, audio_size_bytes = excluded.audio_size_bytes,',
    '  video_storage_path = excluded.video_storage_path, video_mime = excluded.video_mime,',
    '  content = excluded.content, published = true, sort_order = excluded.sort_order, updated_at = now();',
  ].join('\n');
});

const sql = [
  '-- Generated by scripts/demo-lessons/build-seed-sql.mjs from database/demo-lessons/*/lesson.json.',
  '-- Canonical demonstration lessons of the public testing program. Idempotent (upsert by slug).',
  '-- Requires database/migrations/20261125100000_public_testing.sql. Existing participant copies keep',
  '-- the version they were made from (a new version only affects copies created afterwards).',
  'begin;',
  statements.join('\n\n'),
  'commit;',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== sql) {
    console.error('database/seeds/demo_lessons.sql is out of date: run node scripts/demo-lessons/build-seed-sql.mjs');
    process.exit(1);
  }
  console.log('demo seed up to date');
} else {
  writeFileSync(target, sql);
  console.log(`wrote ${path.relative(root, target)} (${slugs.join(', ')}; ${sql.length} bytes)`);
}
