// Builds frontend/js/i18n/phrases/<locale>.js from translation tables
// (JSON objects mapping the Portuguese source to {en, es, "zh-CN"} or null).
// Usage: node scripts/i18n/build-phrases.mjs table1.json table2.json …
// Sources with {0}, {1}… become patterns; the rest are exact phrases. Existing catalogs are merged
// (later tables win), so new tables can extend the catalog without losing earlier work.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const LOCALES = ['en', 'es', 'zh-CN'];
const normalize = (text) => String(text).replace(/\s+/g, ' ').trim();
const holes = (text) => (String(text).match(/\{\d+\}/g) || []).sort().join();

const catalogs = {};
for (const locale of LOCALES) {
  const file = path.join(root, 'frontend/js/i18n/phrases', `${locale}.js`);
  catalogs[locale] = existsSync(file)
    ? (await import(pathToFileURL(file).href)).default
    : { phrases: {}, patterns: [] };
  catalogs[locale].patterns = Object.fromEntries(catalogs[locale].patterns || []);
}
let skipped = 0;
for (const table of process.argv.slice(2)) {
  for (const [rawSource, value] of Object.entries(JSON.parse(readFileSync(table, 'utf8')))) {
    const source = normalize(rawSource);
    if (!value || !source) continue;
    for (const locale of LOCALES) {
      const target = normalize(value[locale] || '');
      if (!target || holes(target) !== holes(source)) {
        skipped += 1;
        continue;
      }
      if (/\{\d+\}/.test(source)) catalogs[locale].patterns[source] = target;
      else catalogs[locale].phrases[source] = target;
    }
  }
}
for (const locale of LOCALES) {
  const { phrases, patterns } = catalogs[locale];
  const sorted = (object) =>
    Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b, 'pt-BR')));
  // Longer patterns first: the most specific template wins.
  const patternList = Object.entries(patterns).sort((a, b) => b[0].length - a[0].length);
  const body = `// Generated by scripts/i18n/build-phrases.mjs — Portuguese interface phrase → ${locale}.\n// Edit the translation tables and rebuild, or edit an entry here directly.\nexport default ${JSON.stringify({ phrases: sorted(phrases), patterns: patternList }, null, 1)};\n`;
  writeFileSync(path.join(root, 'frontend/js/i18n/phrases', `${locale}.js`), body);
  console.log(locale, Object.keys(phrases).length, 'phrases', patternList.length, 'patterns');
}
if (skipped) console.log('skipped (empty or placeholder mismatch):', skipped);
