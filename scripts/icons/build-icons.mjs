// Builds the functional icon sprite and applies it to the static app shell.
// Usage: npm run icons:build   (needs `npm ci` at the repository root for @phosphor-icons/core)
//
// 1. frontend/assets/icons/sprite.svg: one <symbol id="i-<semantic name>"> per entry of ICON_MAP
//    (frontend/js/utils/icons.js), copied from Phosphor's duotone SVGs. The translucent duotone
//    layer gets a CSS-variable fill so pages can tint it (--icon-tint, --icon-tint-opacity).
// 2. frontend/pages/*.html: every legacy hand-written shell icon (sidebar, top bar) is recognised
//    by its drawing and replaced with a sprite reference. Re-running is safe: replaced icons no
//    longer match, so after merging another branch's pages just run the script again.
import { readFile, readdir, writeFile, mkdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICON_MAP, ICON_SPRITE, iconMarkup } from '../../frontend/js/utils/icons.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pack = path.join(root, 'node_modules/@phosphor-icons/core');
const out = path.join(root, 'frontend/assets/icons');

const symbols = [];
for (const [name, source] of Object.entries(ICON_MAP)) {
  const file = path.join(pack, 'assets/duotone', `${source}-duotone.svg`);
  const text = await readFile(file, 'utf8').catch(() => {
    throw new Error(`Phosphor icon "${source}" (for "${name}") not found in ${file}`);
  });
  const inner = text
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(
      /<(path|circle|rect|polygon|ellipse|line|polyline)([^>]*?) opacity="0\.2"/g,
      '<$1$2 class="ph-tint" style="fill:var(--icon-tint,currentColor);opacity:var(--icon-tint-opacity,0.2)"',
    );
  symbols.push(
    `<symbol id="i-${name}" viewBox="0 0 256 256" fill="currentColor"><title>${name}</title>${inner}</symbol>`,
  );
}
await mkdir(out, { recursive: true });
await writeFile(
  path.join(out, 'sprite.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg">
<!-- Phosphor Icons 2.1.1, duotone weight. MIT License, (c) 2023 Phosphor Icons. https://phosphoricons.com -->
<!-- Generated by scripts/icons/build-icons.mjs from frontend/js/utils/icons.js. Do not edit by hand. -->
${symbols.join('\n')}
</svg>
`,
);
await copyFile(path.join(pack, 'LICENSE'), path.join(out, 'PHOSPHOR-LICENSE.txt'));

// ---- Static shell: legacy drawings -> sprite references -------------------------------------
// Each legacy icon is identified by the start of its first path/shape (unique per icon).
const LEGACY = [
  ['<path d="M12 5v14M5 12h14"/>', 'create'],
  ['<path d="M3 11 12 4l9 7"/>', 'home'],
  ['<path d="M4 4h4v16H4zM11 4h4v16h-4zM18 4l4 15-4 1-4-15z"/>', 'library'],
  ['<rect x="3" y="7" width="14" height="13" rx="2"/>', 'review'],
  ['<rect x="3" y="5" width="18" height="16" rx="2"/>', 'plan'],
  ['<circle cx="12" cy="13" r="8"/>', 'focus'],
  ['<circle cx="9" cy="8" r="3"/>', 'classrooms'],
  ['<path d="m9 3-.6 2-2 .9-2-.5-2 3.4', 'settings'],
  ['<path d="M4 6h16M4 12h16M4 18h16"', 'menu'],
  ['<circle cx="12" cy="12" r="8"', 'appearance'],
  ['<path d="M3 8V3h5M16 3h5v5M21 16v5h-5M8 21H3v-5"', 'focus-mode'],
  ['<circle cx="10.5" cy="10.5" r="6.5"/>', 'search'],
  ['<path d="M4 7h10M18 7h2M4 17h4M12 17h8"/>', 'customize'],
  ['<path d="M3 14h18M5 14v6M19 14v6"/>', 'desk'],
  ['<circle cx="12" cy="12" r="9"/><path d="M12 11v6M12 7h.01"/>', 'info'],
  ['<path d="M3 10v4M7 6v12M12 3v18M17 6v12M21 10v4"/>', 'audio'],
  ['<rect x="3" y="6" width="13" height="12" rx="2"/><path d="m16 10 5-3v10l-5-3"/>', 'video'],
  ['<path d="M12 4v11M7.5 10.5 12 15l4.5-4.5M5 20h14"/>', 'download'],
];
const normalise = (s) => s.replace(/\s+/g, ' ').replace(/ \/>/g, '/>').replace(/> </g, '><');

let changed = 0;
const pages = path.join(root, 'frontend/pages');
for (const file of (await readdir(pages)).filter((name) => name.endsWith('.html'))) {
  const full = path.join(pages, file);
  const html = await readFile(full, 'utf8');
  const next = html.replace(/<svg\b([^>]*)>([\s\S]*?)<\/svg\s*>/g, (match, attrs, body) => {
    if (body.includes(`${ICON_SPRITE}#`) || body.includes('<svg')) return match;
    const flat = normalise(body.trim());
    const hit = LEGACY.find(([print]) => flat.startsWith(normalise(print)));
    if (!hit) return match;
    const className =
      /class="([^"]*)"/
        .exec(attrs)?.[1]
        ?.replace(/\bui-icon\b/, '')
        .trim() ?? '';
    // Keep the page's own hooks (for example data-file-icon) on the new element.
    const hooks = [...attrs.matchAll(/\s(data-[\w-]+(?:="[^"]*")?)/g)]
      .map((m) => ` ${m[1]}`)
      .join('');
    return iconMarkup(hit[1], { className }).replace('<svg ', `<svg${hooks} `);
  });
  if (next !== html) {
    await writeFile(full, next);
    changed += 1;
  }
}
console.log(JSON.stringify({ icons: Object.keys(ICON_MAP).length, pagesUpdated: changed }));
